from __future__ import annotations

import csv
import io
import json
import unicodedata
from pathlib import Path

SCRIPT_KEYS = [
    "names", "mkhedruli", "mtavruli", "asomtavruli", "nuskhuri", "homoglyph",
    "phonetic", "braille", "common", "cyrillic", "greek", "armenian", "iso_9984",
    "national", "national_simplified", "bgn", "titus", "qwerty", "numeric",
]
SOURCES = ["mkhedruli", "mtavruli", "asomtavruli", "nuskhuri", "qwerty", "braille"]
REGEX_KEYS = ["mkhedruli", "mtavruli", "asomtavruli", "nuskhuri", "braille", "latin", "cyrillic"]
OUT = Path("packages/rs/crates/anbani-core/src/generated")

def rs_str(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif unicodedata.category(ch) in ("Cf", "Cc"):
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'

def rs_char(ch: str) -> str:
    return "'" + rs_str(ch)[1:-1].replace("'", "\\'").replace('\\"', '"') + "'"

def grouped(mapping: dict[str, int]) -> list[tuple[int, str]]:
    groups: dict[int, list[str]] = {}
    for ch, v in mapping.items():
        groups.setdefault(v, []).append(rs_char(ch))
    return [(v, " | ".join(chs)) for v, chs in groups.items()]

def _unique_object(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"letters.json: duplicate key {key!r}")
        result[key] = value
    return result

def _letters(raw: bytes) -> dict:
    data = json.loads(raw.decode("utf-8"), object_pairs_hook=_unique_object)
    if not isinstance(data, dict) or set(data) != {"alphabets", "regex"}:
        raise ValueError("letters.json: expected exactly alphabets and regex objects")
    tables = data["alphabets"]
    if not isinstance(tables, dict) or list(tables) != SCRIPT_KEYS:
        raise ValueError("letters.json: alphabets must follow the 19 SCRIPT_KEYS in Rust enum order")
    for key, values in tables.items():
        if not isinstance(values, list) or not values or any(not isinstance(v, str) for v in values):
            raise ValueError(f"letters.json: {key} must be a nonempty array of strings")
        if any(0xD800 <= ord(ch) <= 0xDFFF for value in values for ch in value):
            raise ValueError(f"letters.json: {key} contains an unpaired surrogate")
    if len({len(values) for values in tables.values()}) != 1:
        raise ValueError("letters.json: alphabet arrays differ in length")
    regex = data["regex"]
    if not isinstance(regex, dict) or set(regex) != set(REGEX_KEYS) or any(not isinstance(v, str) for v in regex.values()):
        raise ValueError("letters.json: regex must contain the seven string pattern sources")
    return data

def _rows(raw: bytes, name: str, required: set[str]) -> list[dict[str, str]]:
    reader = csv.DictReader(io.StringIO(raw.decode("utf-8"), newline=""), strict=True)
    if reader.fieldnames is None or not required.issubset(reader.fieldnames):
        raise ValueError(f"{name}: missing required CSV columns {sorted(required)}")
    rows = []
    for row in reader:
        if None in row or any(value is None for value in row.values()):
            raise ValueError(f"{name}: malformed CSV row {reader.line_num}")
        rows.append(row)
    return rows

def _tables(tables: dict[str, list[str]]) -> str:
    out = [
        "//! Alphabet tables, reverse index and numeral values.",
        "// GENERATED by packages/py/tools/gen.py from common/data/scripts/letters.json. Do not edit.",
        "",
        "/// Entries per alphabet table (letters, archaic, extended, Svan vowels, punctuation).",
        f"pub const TABLE_LEN: usize = {len(tables['mkhedruli'])};",
        "",
        "/// Every alphabet table in canonical order; index with `Alphabet as usize`.",
        f"pub static TABLES: [[&str; TABLE_LEN]; {len(SCRIPT_KEYS)}] = [",
    ]
    for key in SCRIPT_KEYS:
        out.append(f"    // {key}")
        out.append("    [" + ", ".join(rs_str(s) for s in tables[key]) + "],")
    out.extend([
        "];", "", "/// Alphabet keys in table order (the `from` / `to` names).",
        "pub static TABLE_KEYS: [&str; %d] = [%s];" % (len(SCRIPT_KEYS), ", ".join(rs_str(k) for k in SCRIPT_KEYS)),
        "", "/// First index of `c` in a source alphabet (first wins on duplicates, as Array.indexOf / list.index).",
        "pub fn index_of(source: &str, c: char) -> Option<usize> {", "    match source {",
    ])
    for key in SOURCES:
        seen: dict[str, int] = {}
        for i, s in enumerate(tables[key]):
            if len(s) == 1 and s not in seen:
                seen[s] = i
        arms = ", ".join(f"{alt} => Some({i})" for i, alt in grouped(seen))
        out.append(f"        {rs_str(key)} => match c {{ {arms}, _ => None }},")
    out.extend(["        _ => None,", "    }", "}", ""])
    numerals: dict[str, int] = {}
    for key in ("mkhedruli", "mtavruli", "asomtavruli", "nuskhuri"):
        for ch, v in zip(tables[key], tables["numeric"]):
            if ch and v.isdigit() and ch not in numerals:
                numerals[ch] = int(v)
    out.extend([
        "/// Letter -> numeral value over the four Georgian scripts (anbani.py `toolkit._numeral_map`).",
        "pub fn numeral_value(c: char) -> Option<u32> {", "    match c {",
        "        " + ", ".join(f"{alt} => Some({v})" for v, alt in grouped(numerals)) + ",",
        "        _ => None,", "    }", "}", "",
    ])
    return "\n".join(out)

def _contractions(rows: list[dict[str, str]]) -> str:
    cmap: dict[str, str] = {}
    for row in rows:
        cmap[row["CONTRACTION"]] = row["EXPANSION"]
    emap: dict[str, str] = {}
    for contraction, expansion in cmap.items():
        inc = emap.get(expansion)
        if inc is None or (len(contraction), contraction) < (len(inc), inc):
            emap[expansion] = contraction
    expand_keys = sorted(cmap, key=len, reverse=True)
    contract_keys = sorted(emap, key=len, reverse=True)
    out = [
        "//! Contraction and expansion maps, with the replacer's key orders.",
        "// GENERATED by packages/py/tools/gen.py from common/data/nlp/georgian_contractions.csv. Do not edit.", "",
    ]
    for name, comment, pairs in (
        ("CMAP", "(contraction, expansion) in CSV order (first occurrence of a key).", list(cmap.items())),
        ("EMAP", "(expansion, shortest contraction), insertion order.", list(emap.items())),
        ("EXPAND_KEYS", "Expand keys, longest first, stable: the alternation order of the Python/JS replacer.", [(k, cmap[k]) for k in expand_keys]),
        ("CONTRACT_KEYS", "Contract keys, longest first, stable.", [(k, emap[k]) for k in contract_keys]),
    ):
        out.extend([f"/// {comment}", f"pub static {name}: [(&str, &str); {len(pairs)}] = ["])
        out.extend(f"    ({rs_str(k)}, {rs_str(v)})," for k, v in pairs)
        out.extend(["];", ""])
    return "\n".join(out)

def render(root: Path) -> dict[Path, bytes]:
    letters = _letters((root / "common/data/scripts/letters.json").read_bytes())
    names = ("georgian_contractions.csv", "ambigram_nc5_len7.csv", "ambigram_nc1_len10.csv")
    raw = {name: (root / "common/data/nlp" / name).read_bytes() for name in names}
    contractions = _rows(raw[names[0]], names[0], {"CONTRACTION", "EXPANSION"})
    ambigrams = {name: _rows(raw[name], name, {"MASKED", "NGRAM", "REDUNDANT"}) for name in names[1:]}
    art = [
        "//! N-gram tables that resolve ambiguous Latin letters in georgianisation.",
        "// GENERATED by packages/py/tools/gen.py from common/data/nlp/ambigram_nc5_len7.csv and common/data/nlp/ambigram_nc1_len10.csv. Do not edit.", "",
    ]
    for name, const in zip(names[1:], ("BALANCED", "ACCURATE")):
        pairs = [(r["MASKED"], r["NGRAM"]) for r in ambigrams[name] if r["REDUNDANT"].strip().lower() != "true"]
        art.extend([
            f"/// (masked, ngram) substitution pairs from `{name}`, CSV order, REDUNDANT rows dropped.",
            f"pub static {const}: [(&str, &str); {len(pairs)}] = [",
        ])
        art.extend(f"    ({rs_str(a)}, {rs_str(b)})," for a, b in pairs)
        art.extend(["];", ""])
    js = ["// GENERATED by packages/py/tools/gen.py from common/data/scripts/letters.json. Do not edit.", "export default {", "  alphabets: {"]
    for key, values in letters["alphabets"].items():
        js.append(f"    {json.dumps(key)}: {json.dumps(values, ensure_ascii=False)},")
    js.extend(["  },", "  regex: {"])
    for key, pattern in letters["regex"].items():
        js.append(f"    {json.dumps(key)}: new RegExp({json.dumps(pattern, ensure_ascii=True)}),")
    js.extend(["  }", "};", ""])
    outputs = {
        OUT / "tables.rs": _tables(letters["alphabets"]).encode("utf-8"),
        OUT / "contractions.rs": _contractions(contractions).encode("utf-8"),
        OUT / "ambigrams.rs": "\n".join(art).encode("utf-8"),
        Path("packages/js/anbani/src/lib/data.mjs"): "\n".join(js).encode("utf-8"),
        Path("packages/py/anbani/anbani/data/letters.json"): (json.dumps(letters, ensure_ascii=False, indent=2) + "\n").encode("utf-8"),
    }
    for name in names:
        outputs[Path("packages/py/anbani/anbani/data") / name] = raw[name]
    for name in names[:2]:
        outputs[Path("packages/js/anbani/data") / name] = raw[name]
    return outputs

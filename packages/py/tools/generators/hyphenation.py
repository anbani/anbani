from __future__ import annotations

import re
import sys
from pathlib import Path

def patterns(tex: str) -> list[tuple[str, list[int]]]:
    body = re.search(r"\\patterns\{(.*?)\}", tex, re.S)
    if body is None:
        sys.exit("no \\patterns{} block in hyph-ka.tex")
    out = []
    for pat in body.group(1).split():
        letters, levels = "", [0]
        for ch in pat:
            if ch.isdigit():
                levels[-1] = int(ch)
            else:
                letters += ch
                levels.append(0)
        out.append((letters, levels))
    keys = [k for k, _ in out]
    if len(set(keys)) != len(keys):
        sys.exit("duplicate pattern keys in hyph-ka.tex")
    return sorted(out, key=lambda p: p[0].encode())

def render_patterns(pats: list[tuple[str, list[int]]]) -> str:
    rows = "\n".join(f'    ("{k}", &[{", ".join(map(str, v))}]),' for k, v in pats)
    return (
        "//! TeX hyph-utf8 Georgian hyphenation patterns (hyph-ka v0.3, Levan Shoshiashvili 2013, MIT).\n"
        "// GENERATED by packages/py/tools/gen.py from common/data/phon/hyph-ka.tex. Do not edit; rerun packages/py/tools/gen.py.\n\n"
        "/// Every pattern as (letters with `.` word edges, the level before each letter and after the last), sorted\n"
        "/// by letters.\n"
        f"pub static PATTERNS: [(&str, &[u8]); {len(pats)}] = [\n{rows}\n];\n"
    )

def render(root: Path) -> dict[Path, bytes]:
    source = root / "common/data/phon/hyph-ka.tex"
    text = render_patterns(patterns(source.read_text(encoding="utf-8")))
    return {Path("packages/rs/crates/anbani-core/src/phon/hyph_ka.rs"): text.encode("utf-8")}

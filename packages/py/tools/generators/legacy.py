from __future__ import annotations

import math
from pathlib import Path

MKHEDRULI = [chr(c) for c in range(0x10D0, 0x10F1)]
LATIN = "abcdefghijklmnopqrstuvwxyz"
SCALE = 4

def rows(source: Path, name: str) -> list[list[str]]:
    out = [line.split("\t") for line in (source / name).read_text(encoding="utf-8").splitlines() if line and not line.startswith("# ")]
    return out[1:]

def rs_char(c: str) -> str:
    return "'\\''" if c == "'" else "'\\\\'" if c == "\\" else f"'{c}'"

def generate(source: Path) -> str:
    out = [
        "//! Legacy code pages, font encodings, keyboard layouts and the letter-trigram costs.",
        "// GENERATED by packages/py/tools/gen.py from common/data/legacy/*.tsv. Do not edit; edit the TSVs and rerun packages/py/tools/gen.py.",
        "",
    ]
    pages = rows(source, "codepages.tsv")
    for col, name in enumerate(("ACADEMY", "PS", "GEOSTD8"), start=1):
        out.append(f"/// Upper half (0x80-0xFF) of the {name.lower()} code page; `None` = undefined byte.")
        cells = []
        for r in pages:
            cells.append("None" if r[col] == "-" else f"Some('\\u{{{r[col][2:]}}}')")
        out.append(f"pub static {name}: [Option<char>; 128] = [{', '.join(cells)}];")
    out.append("")
    fonts = rows(source, "fonts.tsv")
    for col, name in enumerate(("ACADNUSX", "LITNUSX", "ACADMTAVR"), start=1):
        out.append(f"/// What the {name.lower()} font draws for a stored character; anything else is drawn as itself.")
        out.append(f"pub fn {name.lower()}(c: char) -> Option<char> {{")
        arms = [f"{rs_char(r[0])} => Some({rs_char(r[col])})," for r in fonts if r[col] != "-"]
        out.append("    match c { " + " ".join(arms) + " _ => None }")
        out.append("}")
    out.append("")
    lay = rows(source, "layouts.tsv")
    names = ("US", "GE", "RU", "GE_RU")
    out.append("/// Keys (xkb name, level 1 or 2) in layouts.tsv order; the layout tables below are parallel to it.")
    keys = ", ".join('("%s", %s)' % (r[0], r[1]) for r in lay)
    out.append(f"pub static KEYS: [(&str, u8); {len(lay)}] = [{keys}];")
    for col, name in enumerate(names, start=2):
        out.append(f"/// The character each key types under xkb `{name.lower()}`; `None` = nothing at that level.")
        cells = ["None" if r[col] == "NONE" else f"Some({rs_char(r[col])})" for r in lay]
        out.append(f"pub static {name}: [Option<char>; {len(lay)}] = [{', '.join(cells)}];")
    out.append("")
    for name, alphabet in (("KA", MKHEDRULI), ("EN", list(LATIN))):
        n = len(alphabet) + 1
        out.append(f"/// Symbols of the {name.lower()} trigram model: letters 0..{n - 2}, word boundary {n - 1}.")
        out.append(f"pub const {name}_SYMBOLS: usize = {n};")
        out.append(f"/// {name.lower()} trigram costs, round(-log2 P(c | a b) * {SCALE}) add-one smoothed, at `(a * n + b) * n + c`.")
        out.append(f'pub static {name}_TRIGRAM_COST: &[u8; {n ** 3}] = include_bytes!("{name.lower()}3.bin");')
    return "\n".join(out) + "\n"

def trigram_costs(source: Path, name: str, alphabet: list[str]) -> bytes:
    index = {c: i for i, c in enumerate(alphabet + ["#"])}
    n = len(index)
    counts = [0] * n**3
    for tri, count in rows(source, name):
        a, b, c = (index[x] for x in tri)
        counts[(a * n + b) * n + c] = int(count)
    out = bytearray()
    for ctx in range(n * n):
        row = counts[ctx * n : ctx * n + n]
        total = sum(row) + n
        out += bytes(min(255, round(-math.log2((x + 1) / total) * SCALE)) for x in row)
    return bytes(out)

def render(root: Path) -> dict[Path, bytes]:
    source = root / "common/data/legacy"
    output = Path("packages/rs/crates/anbani-core/src/legacy")
    return {
        output / "tables.rs": generate(source).encode("utf-8"),
        output / "ka3.bin": trigram_costs(source, "trigrams-ka.tsv", MKHEDRULI),
        output / "en3.bin": trigram_costs(source, "trigrams-en.tsv", list(LATIN)),
    }

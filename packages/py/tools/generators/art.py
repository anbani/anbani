JS_WHITESPACE = set("\t\n\v\f\r \u00a0\u1680\u2028\u2029\u202f\u205f\u3000\ufeff") | {
    chr(c) for c in range(0x2000, 0x200B)
}
ART = Path("packages/rs/crates/anbani-core/src/art")
TEXTART = Path("packages/js/textart/src")

def utf16_len(s: str) -> int:
    return len(s.encode("utf-16-le")) // 2

def js_trim_start(s: str) -> str:
    i = 0
    while i < len(s) and s[i] in JS_WHITESPACE:
        i += 1
    return s[i:]

def js_trim_end(s: str) -> str:
    i = len(s)
    while i > 0 and s[i - 1] in JS_WHITESPACE:
        i -= 1
    return s[:i]

def build_letter(art: str, height: int) -> list[str]:
    lines = art.split("\n")[1 : 1 + height]
    lengths = [utf16_len(x) for x in lines]
    max_length = int(sorted(str(n) for n in lengths)[-1])
    if max_length != max(lengths):
        raise ValueError(f"buildLetter's string sort misreads glyph widths {lengths}; port that case first")
    padded = [x + " " * (max_length - utf16_len(x)) if utf16_len(x) < max_length else x for x in lines]
    left = min(utf16_len(x) - utf16_len(js_trim_start(x)) for x in padded)
    right = min(utf16_len(x) - utf16_len(js_trim_end(x)) for x in padded)
    rows = [x[left:] for x in padded]
    rows = [x[: len(x) - right] for x in rows]
    if any(ord(c) > 0xFFFF for r in rows for c in r):
        raise ValueError("a glyph holds a non-BMP character: the UTF-16 slicing above needs porting")
    return rows

def slug(title: str) -> str:
    return re.sub(r"^anbani-", "", title.lower().replace(" ", "-"))

class JsFont:

    def __init__(self, cls: str, title: str, defs: dict | None):
        self.cls, self.title = cls, title
        self.glyphs: dict[str, list[str]] = {}
        if defs is None:
            self.height, self.author = 0, "Anbani.ge"
            return
        self.height, self.author = defs["height"], defs["author"]["name"]
        for element in defs["font"]:
            self.glyphs[element["letter"]] = build_letter(element["art"], self.height)

def rs_str(s: str) -> str:
    if unicodedata.normalize("NFC", s) != s:
        return '"' + "".join(ch if ord(ch) < 0x80 else "\\u{%X}" % ord(ch) for ch in s) + '"'
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif unicodedata.category(ch) in ("Cf", "Cc"):
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'

def rs_char(ch: str) -> str:
    return "'" + rs_str(ch)[1:-1].replace("'", "\\'").replace('\\"', '"') + "'"

def render_fonts(fonts: list[JsFont]) -> bytes:
    kinds = {"BlockFont": "Kind::Block", "LineFont": "Kind::Line", "SampleFont": "Kind::Sample"}
    out = [
        "//! `TextArt` fonts: every glyph after `BlockFont.buildLetter`, sorted by letter.",
        "// GENERATED by packages/py/tools/gen.py from common/data/textart/{BlockFont,LineFont}/*.yml and",
        "// common/data/textart/collection.json (GPL-3.0-or-later). Do not edit; rerun packages/py/tools/gen.py.",
        "",
        "use super::{Font, Kind};",
        "",
        "/// Every font `TextArt`'s `Collection.mjs` exposes, in its order.",
        f"pub static FONTS: [Font; {len(fonts)}] = [",
    ]
    for font in fonts:
        out.append(
            f"    Font {{ key: {rs_str(slug(font.title))}, title: {rs_str(font.title)}, "
            f"author: {rs_str(font.author)}, height: {font.height}, kind: {kinds[font.cls]}, glyphs: &["
        )
        for letter in sorted(font.glyphs, key=ord):
            rows = ", ".join(rs_str(row) for row in font.glyphs[letter])
            out.append(f"        ({rs_char(letter)}, &[{rows}]),")
        out.append("    ] },")
    out.append("];")
    return ("\n".join(out) + "\n").encode("utf-8")

def render_homoglyphs(root: Path) -> bytes:
    source = root / "common/data/vendor/homoglyph"
    data = json.loads((source / "homoglyph.json").read_text(encoding="utf-8"))
    meta = json.loads((source / "homoglyph.meta.json").read_text(encoding="utf-8"))
    if not isinstance(meta, dict):
        raise ValueError("homoglyph.meta.json must contain an object")
    if data["schema"] != 2:
        raise ValueError(f"homoglyph.json schema {data['schema']}; this renderer reads schema 2")
    if len(data["alphabet"]) != len(data["cand"]):
        raise ValueError("homoglyph alphabet and candidate arrays differ in length")
    licence = (source / "LICENSE").read_text(encoding="utf-8").split("\n---")[0].strip()
    if not licence:
        raise ValueError("homoglyph LICENSE must not be empty")
    out = [
        "//! Ranked homoglyphs per modern Mkhedruli letter, best first.",
        "// GENERATED by packages/py/tools/gen.py from common/data/vendor/homoglyph/{homoglyph.json,homoglyph.meta.json,LICENSE}.",
        "// Do not edit; rerun packages/py/tools/gen.py. The data is under the MIT licence of Anbani/homoglyph:",
        "//",
        *[("// " + line).rstrip() for line in licence.splitlines()],
        "",
        "use super::homoglyph::Candidate;",
        "",
        "/// The 33 letters, in the dataset's (alphabet) order, each with its candidates.",
        f"pub static HOMOGLYPHS: [(char, &[Candidate]); {len(data['alphabet'])}] = [",
    ]
    for letter, candidates in zip(data["alphabet"], data["cand"]):
        if not isinstance(letter, str) or len(letter) != 1 or 0xD800 <= ord(letter) <= 0xDFFF:
            raise ValueError("homoglyph alphabet entries must be Unicode scalar characters")
        out.append(f"    ({rs_char(letter)}, &[")
        for candidate in candidates:
            if [ord(x) for x in candidate["c"]] != candidate["cp"]:
                raise ValueError(f"{letter}: c and cp disagree for {candidate}")
            score, margin = float(candidate["s"]), float(candidate["m"])
            if not math.isfinite(score) or not math.isfinite(margin):
                raise ValueError(f"{letter}: homoglyph score and margin must be finite")
            wrap = f"Some({rs_str(candidate['w'])})" if "w" in candidate else "None"
            out.append(
                f"        Candidate {{ glyph: {rs_str(candidate['c'])}, wrap: {wrap}, score: {score!r}, "
                f"margin: {margin!r}, script: {rs_str(data['scripts'][candidate['sc']])}, "
                f"block: {rs_str(data['blocks'][candidate['bl']])}, "
                f"font: {rs_str(data['fonts'][candidate['ft']])}, flags: {candidate['f']} }},"
            )
        out.append("    ]),")
    out.append("];")
    return ("\n".join(out) + "\n").encode("utf-8")

def render_collection(collection: list[dict]) -> bytes:
    out = [
        "// GENERATED by packages/py/tools/gen.py from common/data/textart/collection.json. Do not edit.",
        "import SampleFont from '../fonts/SampleFont/SampleFont.mjs';",
        "import BlockFont from '../fonts/BlockFont/BlockFont.mjs';",
        "import LineFont from '../fonts/LineFont/LineFont.mjs';",
        "import BlockFontDefs from '../fonts/BlockFont/BlockFontDefinitions.mjs';",
        "import LineFontDefs from '../fonts/LineFont/LineFontDefinitions.mjs';",
        "",
        "const fonts = [",
    ]
    for item in collection:
        kind, title = item["kind"], item["title"]
        if kind == "SampleFont":
            out.append("  new SampleFont(),")
        else:
            out.append(f"  new {kind}({json.dumps(title, ensure_ascii=False)}, {kind}Defs),")
    out.extend([
        "];",
        "",
        "const collection = {};",
        "fonts.forEach((font) => {",
        "  collection[font.title] = font;",
        "});",
        "",
        "export default collection;",
    ])
    return ("\n".join(out) + "\n").encode("utf-8")

def render(root: Path) -> dict[Path, bytes]:
    helper = JS_ROOT / "tools/generators/textart.mjs"
    parsed = json.loads(subprocess.check_output(
        ["node", str(helper), "--data-root", str((root / "common/data/textart").resolve())],
        text=True,
        encoding="utf-8",
        timeout=60,
    ))
    definitions, collection = parsed["definitions"], parsed["collection"]
    fonts = [
        JsFont(item["kind"], item["title"],
               None if item["kind"] == "SampleFont" else definitions[item["kind"]][item["title"]])
        for item in collection
    ]
    outputs = {}
    for kind, fonts_by_title in definitions.items():
        warning = (
            f"// GENERATED by packages/py/tools/gen.py from common/data/textart/{kind}/*.yml. Do not edit.\n"
        )
        body = warning + "export default " + json.dumps(
            fonts_by_title, ensure_ascii=False, separators=(",", ":")
        ) + "\n"
        outputs[TEXTART / "fonts" / kind / f"{kind}Definitions.mjs"] = body.encode("utf-8")
    outputs[TEXTART / "lib/Collection.mjs"] = render_collection(collection)
    outputs[ART / "fonts.rs"] = render_fonts(fonts)
    outputs[ART / "homoglyphs.rs"] = render_homoglyphs(root)
    return outputs

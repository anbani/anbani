from __future__ import annotations

import json
import unicodedata
from pathlib import Path

from generators.tables import rs_str as _rs_str

SOURCE = "common/data/scripts/morse.json"
DIRECT_GROUPS = ("letters", "extended_letters", "combining_marks", "digits", "punctuation")
TOP_KEYS = [
    "name", "status", "languages", "script", *DIRECT_GROUPS[:3], "digits", "punctuation",
    "laz_latin_profile", "timing_units", "text_serialization", "unicode_escape", "rules",
]
CODE = set(".-")

def rs_str(text: str) -> str:
    return "".join("\\u{%X}" % ord(ch) if unicodedata.category(ch) == "Mn" else ch for ch in _rs_str(text))

def rs_char(ch: str) -> str:
    return "'" + rs_str(ch)[1:-1].replace("'", "\\'").replace('\\"', '"') + "'"

def _unique_object(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"morse.json: duplicate key {key!r}")
        result[key] = value
    return result

def _layout(raw: bytes) -> dict:
    data = json.loads(raw.decode("utf-8"), object_pairs_hook=_unique_object)
    if not isinstance(data, dict) or sorted(data) != sorted(TOP_KEYS):
        raise ValueError(f"morse.json: expected keys {TOP_KEYS}")
    direct: dict[str, str] = {}
    for group in DIRECT_GROUPS:
        for char, code in data[group].items():
            if len(char) != 1 or not code or set(code) - CODE:
                raise ValueError(f"morse.json: {group} {char!r} must be one scalar with a dot/dash code")
            direct[char] = code
    if len(set(direct.values())) != len(direct):
        raise ValueError("morse.json: direct codes must be unique so decoding is unambiguous")
    if sorted(data["digits"]) != list("0123456789"):
        raise ValueError("morse.json: digits must be exactly 0-9")
    escape = data["unicode_escape"]["token"]
    serial = data["text_serialization"]
    if escape in direct.values() or serial["word_separator_token"] in direct.values() or serial["token_separator"] != " ":
        raise ValueError("morse.json: escape / word tokens collide with a code, or the token separator is not a space")
    latin = data["laz_latin_profile"]["latin_to_mkhedruli"]
    if any(georgian not in direct for georgian in latin.values()):
        raise ValueError("morse.json: every Laz letter must map to a directly coded Mkhedruli letter")
    if any(spelling not in latin for spelling in data["laz_latin_profile"]["spelling_aliases"].values()):
        raise ValueError("morse.json: spelling aliases must point at profile spellings")
    return data

def _direct(data: dict) -> dict[str, str]:
    out: dict[str, str] = {}
    for group in DIRECT_GROUPS:
        out.update(data[group])
    return out

def laz_matches(data: dict) -> list[tuple[str, str]]:
    profile = data["laz_latin_profile"]
    latin = profile["latin_to_mkhedruli"]
    spellings: dict[str, str] = {}
    for spelling, georgian in latin.items():
        spellings[spelling] = georgian
        spellings[unicodedata.normalize("NFD", spelling)] = georgian
    for alias, spelling in profile["spelling_aliases"].items():
        spellings[alias] = latin[spelling]
        spellings[unicodedata.normalize("NFD", alias)] = latin[spelling]
    if any(ord(ch) > 0xFFFF for s in spellings for ch in s):
        raise ValueError("morse.json: Laz spellings must stay in the BMP (UTF-16 and code-point lengths agree)")
    return sorted(spellings.items(), key=lambda kv: len(kv[0]), reverse=True)

def _rust(data: dict) -> str:
    direct = _direct(data)
    reverse_latin: dict[str, str] = {}
    for spelling, georgian in data["laz_latin_profile"]["latin_to_mkhedruli"].items():
        reverse_latin[georgian] = spelling
    matches = laz_matches(data)
    out = [
        "//! Kartvelian Morse layout (proposed): direct codes, Laz Latin spellings and the reserved tokens.",
        f"// GENERATED by packages/py/tools/gen.py from {SOURCE}. Do not edit.", "",
        f"/// Layout name.\npub const NAME: &str = {rs_str(data['name'])};",
        f"/// Layout status (`proposed` until adopted).\npub const STATUS: &str = {rs_str(data['status'])};",
        f"/// Token that starts a seven-digit decimal Unicode escape.\npub const ESCAPE: &str = {rs_str(data['unicode_escape']['token'])};",
        f"/// Token for one space.\npub const WORD: &str = {rs_str(data['text_serialization']['word_separator_token'])};",
        "", "/// (character, code): letters, extended letters, combining marks, digits, punctuation.",
        f"pub static DIRECT: [(char, &str); {len(direct)}] = [",
    ]
    out.extend(f"    ({rs_char(ch)}, {rs_str(code)})," for ch, code in direct.items())
    out.extend(["];", "", "/// Digit codes, 0-9 in order.", "pub static DIGITS: [&str; 10] = ["])
    out.extend(f"    {rs_str(data['digits'][d])}," for d in "0123456789")
    out.extend([
        "];", "", "/// (Laz Latin spelling, Mkhedruli letter), longest first: NFC and NFD forms, then the aliases.",
        f"pub static LAZ: [(&str, char); {len(matches)}] = [",
    ])
    out.extend(f"    ({rs_str(s)}, {rs_char(g)})," for s, g in matches)
    out.extend(["];", "", "/// Mkhedruli letter -> its Laz Latin spelling (last profile entry wins).",
                f"pub static LAZ_REVERSE: [(char, &str); {len(reverse_latin)}] = ["])
    out.extend(f"    ({rs_char(g)}, {rs_str(s)})," for g, s in reverse_latin.items())
    out.extend(["];", ""])
    return "\n".join(out)

def _js(data: dict) -> str:
    body = json.dumps(data, ensure_ascii=False, indent=4)
    return "\n".join([
        f"// GENERATED by packages/py/tools/gen.py from {SOURCE}. Do not edit.",
        "// Proposed Kartvelian Morse layout, independent of the positional alphabet tables.",
        "const freeze = (value) => {",
        "    for (const child of Object.values(value))",
        '        if (child && typeof child === "object") freeze(child);',
        "    return Object.freeze(value);",
        "};",
        "",
        f"export default freeze({body});",
        "",
    ])

def render(root: Path) -> dict[Path, bytes]:
    raw = (root / SOURCE).read_bytes()
    data = _layout(raw)
    return {
        Path("packages/js/anbani/src/lib/morse-layout.mjs"): _js(data).encode("utf-8"),
        Path("packages/py/anbani/anbani/data/morse.json"): raw,
        Path("packages/rs/crates/anbani-core/src/generated/morse.rs"): _rust(data).encode("utf-8"),
    }

#!/usr/bin/env python3
"""Materialize package-local data from canonical sources; --check never writes."""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

from generators import art, hyphenation, legacy, morphology, morse, tables
from repo_paths import REPO_ROOT

ROOT = REPO_ROOT
PURE = {
    "js": Path("packages/js/anbani"),
    "python": Path("packages/py/anbani"),
    "textart": Path("packages/js/textart"),
}
RUST_DISTRIBUTIONS = [
    Path("packages/rs/crates") / name
    for name in (
        "anbani-core", "anbani-api", "anbani-spell", "anbani-tui", "anbani-mcp",
        "anbani-cli", "anbani-py", "anbani-napi", "anbani-cabi", "anbani-wasm",
    )
] + [Path("packages/js/native"), Path("packages/js/wasm"), Path("packages/py/anbani-rs")]

def source_manifest(root: Path) -> dict:
    manifest = json.loads((root / "common/data/manifest.json").read_text(encoding="utf-8"))
    if manifest.get("schema") != 1 or not isinstance(manifest.get("sources"), list):
        raise ValueError("common/data/manifest.json: expected schema 1 and sources array")
    seen = set()
    for source in manifest["sources"]:
        path = Path(source["path"])
        if path.is_absolute() or ".." in path.parts or path in seen:
            raise ValueError(f"common/data/manifest.json: invalid or duplicate source {path}")
        seen.add(path)
        origin = source.get("origin")
        if not source.get("license") or (origin is not None and not all(origin.get(k) for k in ("repo", "commit", "path"))):
            raise ValueError(f"common/data/manifest.json: missing license/origin for {path}")
        raw = (root / "common" / path).read_bytes()
        if path.is_relative_to("data/vendor") and "sha256" not in source:
            raise ValueError(f"common/data/manifest.json: missing external checksum for {path}")
        if "sha256" in source and hashlib.sha256(raw).hexdigest() != source["sha256"]:
            raise ValueError(f"external checksum mismatch: {path}")
    return manifest


def distribution_outputs(root: Path, manifest: dict) -> dict[Path, bytes]:
    sources = manifest["sources"]
    outputs = {}
    for family, package in PURE.items():
        selected = [source for source in sources if family in source["consumers"]]
        outputs[package / "NOTICE"] = _notice(root, selected, rust=False)
    rust_sources = [source for source in sources if "rust" in source["consumers"]]
    rust_notice = _notice(root, rust_sources, rust=True)
    license_bytes = (root / "LICENSE").read_bytes()
    for package in RUST_DISTRIBUTIONS:
        outputs[package / "LICENSE"] = license_bytes
        outputs[package / "NOTICE"] = rust_notice
    snapshots = {
        Path("packages/js/anbani/spec/golden.json"): "golden.json",
        Path("packages/py/anbani/spec/golden.json"): "golden.json",
        Path("packages/js/textart/spec/golden-art.json"): "golden-art.json",
    }
    snapshots.update({Path("packages/rs/crates/anbani-api/tests/spec") / name: name for name in ("golden.json", "golden-rs.json", "golden-art.json")})
    for target, name in snapshots.items():
        outputs[target] = (root / "common/spec" / name).read_bytes()
    return outputs

def build_outputs(root: Path) -> dict[Path, bytes]:
    root = root.resolve()
    manifest = source_manifest(root)
    outputs = {}
    for rendered in [
        tables.render(root), art.render(root), hyphenation.render(root),
        morphology.render(root), legacy.render(root), morse.render(root), distribution_outputs(root, manifest),
    ]:
        for path, raw in rendered.items():
            if path.is_absolute() or ".." in path.parts or path in outputs:
                raise ValueError(f"invalid or duplicate managed output: {path}")
            if not isinstance(raw, bytes):
                raise TypeError(f"renderer did not return bytes: {path}")
            outputs[path] = raw
    return outputs

def check_outputs(root: Path, outputs: dict[Path, bytes]) -> list[Path]:
    stale = []
    for path, expected in outputs.items():
        actual = root / path
        if not actual.is_file() or actual.read_bytes() != expected:
            stale.append(path)
    return stale

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare freshly rendered bytes without writes")
    args = parser.parse_args(argv)
    try:
        outputs = build_outputs(ROOT)
        stale = check_outputs(ROOT, outputs)
        if args.check:
            for path in stale:
                print(f"stale or missing: {path}", file=sys.stderr)
            if stale:
                print("Run python packages/py/tools/gen.py", file=sys.stderr)
            else:
                print(f"Generated artifacts are current ({len(outputs)} outputs).")
            return int(bool(stale))
        for path in stale:
            destination = ROOT / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(outputs[path])
            print(f"wrote {path}")
        print(f"Generated {len(outputs)} artifacts; {len(stale)} changed.")
        return 0
    except (OSError, ValueError, TypeError, KeyError, subprocess.SubprocessError) as error:
        print(f"generation failed: {error}", file=sys.stderr)
        return 1

if __name__ == "__main__":
    sys.exit(main())
